/* ══════════════════════════════════════════════════════════════
   마음의 향기 타로 — 위험한 말 알아차리기 (아이 보호)
   ══════════════════════════════════════════════════════════════
   학생이 쓴 고민 한 줄이나 질문에 '죽고 싶다', '맞는다', '괴롭힘' 같은 말이 보이면
   카드 풀이를 멈추고 도움 안내를 보여 주기 위한 파일이에요.
   인터넷·AI 연결 없이 기기 안에서만 확인하고, 앱(index.html)과 서버(api/ask.js)가 함께 써요.

   ⚠️ 고칠 때
     - 아래 규칙은 '띄어쓰기·문장부호를 모두 지운 글'에 맞춰 봅니다. (예: "죽 고 싶 어" → "죽고싶어")
     - 고친 뒤에는 꼭  node --test tests/  로 확인하세요. tests/safety.test.js 에
       반드시 잡아야 하는 말과 잡으면 안 되는 말(예: "배고파 죽겠어")이 들어 있어요.
     - 오래된 아이패드(사파리 16.3 이하)에서도 돌아가도록, 앞 글자를 되돌아보는 정규식(lookbehind)은 쓰지 않아요.
   ══════════════════════════════════════════════════════════════ */
(function(){
"use strict";

/* 띄어쓰기·문장부호·이모지·보이지 않는 글자를 지우고, 같은 글자가 3번 넘게 이어지면 하나로 줄임 */
function normalize(t){
  return String(t==null?"":t).normalize("NFC").toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu,"")
    .replace(/(.)\1{2,}/gu,"$1");
}

/* 위험한 말과 글자가 겹치지만 뜻은 괜찮은 말 — 검사 전에 지워 둡니다
   (과자 살래→'자살', 수학 대회→'학대', 숫자 해석→'자해', 과목 매일→'목매', 때려치우다, 정답 맞았어 …) */
const SCRUB=new RegExp([
  "[때떄]려치",
  "(?:정답|답|문제|점수|시간|박자|줄|짝)(?:을|를|이|가)?맞",
  "형광|형태|형식|형편|형성|모형|인형|원형|정형|외형|지형|변형|성형|유형|체형|도형|대형|소형|중형|신형|구형|조형",
  "과자|모자|의자|액자|상자|피자|감자|남자|여자|왕자|부자|글자|숫자|타자|팔자|사자",
  "수학|과학|입학|방학|개학|휴학|문학|화학|진학|전학|대학|중학|견학|통학|철학|의학|법학",
  "과목|항목|제목|종목|품목",
  "숙제가|문제가|과제가|주제가",
  "(?:강아지|고양이|햄스터|토끼|동물|인형|애완동물|반려동물)(?:의)?(?:몸|털)",
  "(?:모기|벌레|바퀴벌레|바퀴|파리|개미|좀비|몬스터|보스|악당)(?:를|을)?(?:죽여버|죽일|죽이고|죽어야)",
  "(?:몬스터|보스|악당|좀비|캐릭터|공|북|드럼|벽)(?:를|을|에서)?[때떄](?:리|린|릴|렸|려)",
  "(?:카드|그림|탑)(?:에서|속|속에서|에|의)?(?:사람이|사람들이|사람)뛰어내",
  "뛰어내리는(?:사람|그림|카드)",
  "(?:학교폭력|학폭|폭력)(?:예방|교육)|폭력적"
].join("|"),"gu");

/* 때리거나 만지는 사람 */
const ACT="(?:아빠|엄마|아버지|어머니|부모|새엄마|새아빠|할머니|할아버지|선생|쌤|형|오빠|누나|언니|삼촌|이모|고모|어른|아저씨|아줌마|친구|애들|선배|걔|쟤)";
const HIT="(?:[때떄](?:리|린|릴|렸|려|림)|폭력|폭행)";
const TOUCH="만(?:지|져|졌|짐)";

/* [종류, 규칙] — 위에서부터 차례로 보고 처음 걸린 종류를 돌려줍니다 */
const RULES=[
  ["self_harm",[
    "죽[고구](?:싶|십|시퍼|시프|파|퍼)","주꼬(?:싶|십|시퍼)",
    "자살(?=$|하|할|했|해|한|시|충|생|각|이|을|은|는|도|까지|밖|뿐|같|방법|싶|말|소리|얘|의|로|에|만|ㅠ|ㅜ|ㅋ)",
    "자해(?=$|하|할|했|해|한|를|을|는|은|도|흔|상처|충|생|자국|이|가|까지|같|싶|의|로|에|만|방법|ㅠ|ㅜ|ㅋ)",
    "살기(?:가)?(?:싫|실|시러)","살고(?:싶|십)지(?:않|안)","(?:살|사는)이유가?없","사는게(?:싫|의미없|지겨)",
    "(?:사라지|없어지|사라져버리|없어져버리)[고구](?:싶|십|시퍼|파)",
    "(?:내가|나는|제가|저는|나만|저만)(?:그냥|차라리|빨리|확|진짜)?(?:사라지|없어지|죽으)면",
    "(?:나|저|내)같은(?:건|거|애|놈|사람)(?:은|는)?(?:없어져야|사라져야|죽어야|필요없|태어나지)",
    "태어나지(?:말|않았으면)","안태어났으면",
    "뛰어내(?:리|릴|려|렸)",
    "목(?:을)?(?:매(?!일|번|주|년)|맬|맸)",
    "손목(?:을|에)?(?:긋|그어|그었|그을|칼|커터|자르|베)",
    "목숨(?:을)?(?:끊|버리)","극단적(?:인)?선택",
    "죽어버(?:리|릴|려|렸)","죽어야(?:지|겠|돼|되|해|할)","죽으려(?:고|해|한다|구)","차라리죽","죽는게(?:나아|낫|편)"
  ]],
  ["sexual",[
    "성(?:추행|폭력|폭행|희롱|학대)","강간",
    "몸(?:을|를)?"+TOUCH,
    "(?:가슴|엉덩이|속옷|팬티|중요한곳|중요부위)(?:을|를|에|도)?(?:"+TOUCH+"|보여달|보여줘|찍)",
    ACT+"(?:이|가|께서|는|은)?(?:자꾸|계속|몰래|억지로|막|자주)?(?:나를|날|저를|절|내몸을?|제몸을?)?(?:자꾸|계속|몰래|억지로|막)?"+TOUCH,
    "옷을?벗으라|벗으라고|(?:벗은|알몸|야한|몸)사진"
  ]],
  ["abuse",[
    ACT+".{0,15}"+HIT,
    ACT+"(?:한테|에게|께|한테서|에게서).{0,10}맞(?:았|아서|아|고|는|을|음)",
    "(?:나를|날|저를|절|나도|저도)(?:자꾸|계속|매일|맨날|막|또|자주)?"+HIT,
    "(?:매일|맨날)맞(?:아|았|고|는|을)",
    "학대(?=$|하|해|했|한|를|을|당|받|는|은|도|야|라|예|에|인|같|가|신고|이|의|로|ㅠ|ㅜ)",
    "가정폭력","(?:폭력|폭행)(?:을|를)?당",
    "(?:뺨|따귀|싸대기|머리|얼굴)(?:을|를)?(?:맞|[때떄](?:리|려|렸))",
    "(?:맞아서|맞고|[때떄]려서)(?:멍|피가|다쳤)"
  ]],
  ["bullying",[
    "왕따","은따","따돌","괴롭(?:히|혀|힘|혔|힌|힐)",
    "학폭","학교폭력","사이버폭력","언어폭력",
    "단톡(?:방)?(?:에서)?(?:나를?|저를?|날|절)?(?:욕|저격|강퇴)",
    "(?:애들|친구들|걔네|쟤네|걔들|쟤들|선배들)(?:이|가)?(?:나를?|저를?|날|절)?(?:자꾸|계속|매일|맨날|막|다같이)?(?:욕해|욕했|욕하|놀려|놀렸|무시해|무시했)"
  ]],
  ["danger",[
    "협박","납치","죽여버(?:리|릴|려|렸)","죽일(?:거|꺼|게|래)","죽이고(?:싶|십)",
    "가출(?=$|하|할|했|해|한|을|를|각|충동|생각|싶|이)","칼로(?:찌|찔)","찔러(?:버리|죽)"
  ]]
].map(([cat,list])=>[cat,new RegExp(list.join("|"),"u")]);

/* 위험한 말이 있으면 {cat:'self_harm'|'sexual'|'abuse'|'bullying'|'danger'}, 없으면 null */
function check(text){
  const s=normalize(text).replace(SCRUB,"·");
  if(!s)return null;
  for(const [cat,re] of RULES)if(re.test(s))return {cat};
  return null;
}

/* AI에게 보내기 전에 전화번호·이메일·긴 숫자를 가림 (학생 화면에도 가린 그대로 보여 줌) */
function redact(t){
  return String(t==null?"":t)
    .replace(/[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+/g,"[이메일]")
    .replace(/(?:\+?82[ .-]?|0)1[016789][ .-]?\d{3,4}[ .-]?\d{4}/g,"[전화번호]")
    .replace(/0\d{1,2}[ .-]?\d{3,4}[ .-]?\d{4}/g,"[전화번호]")
    .replace(/\d{6,}/g,"[숫자]");
}

/* 도움 안내 문구 — 앱의 도움 안내 화면과 서버 답변이 함께 씁니다. 번호를 바꿀 땐 prompts.js 도 같이 보세요. */
const HELP={
  title:"말해 줘서 정말 고마워요",
  body:["그건 네 잘못이 아니에요. 혼자 견디지 않아도 돼요.","지금 같은 방에 계신 선생님께 이 화면을 보여 주세요."],
  linesLabel:"전화나 문자로도 도움을 받을 수 있어요",
  lines:[["1388","청소년상담","전화·문자·카카오톡"],["109","자살예방상담",""],["117","학교폭력 신고",""],["112","위급할 때",""]]
};
const HELP_TEXT=[HELP.title+".",...HELP.body,HELP.linesLabel+": "+HELP.lines.map(([n,name,how])=>`${name} ${n}${how?`(${how})`:""}`).join(" · ")].join("\n");

/* AI가 위험한 이야기라고 판단하면 답 맨 앞에 붙이는 표시 (prompts.js 의 안전 규칙) */
const MARKER="[도움필요]";
const hasMarker=t=>/\[\s*도움\s*필요\s*\]/.test(String(t||""));

const Safety={normalize,check,redact,HELP,HELP_TEXT,MARKER,hasMarker};
if(typeof module==="object"&&module.exports)module.exports=Safety;
if(typeof window!=="undefined")window.Safety=Safety;
})();
